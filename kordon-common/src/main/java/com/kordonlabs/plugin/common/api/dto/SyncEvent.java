package com.kordonlabs.plugin.common.api.dto;

/**
 * One element of {@code SyncRequest.events}. On the wire each event is an object with a discriminator {@code "t"}
 * ("join" | "info" | "quit") next to the record's fields. {@code ago} is the number of milliseconds since the event,
 * computed at send time and clamped to {@link #MAX_AGO_MS}.
 */
public sealed interface SyncEvent permits SyncEvent.Join, SyncEvent.Info, SyncEvent.Quit {

    /** 7 days: the panel skips events with a larger {@code ago}. */
    long MAX_AGO_MS = 604_800_000L;

    String JOIN = "join";
    String INFO = "info";
    String QUIT = "quit";

    /** Session id: a random UUID v4 generated by the plugin per connection (lower-case, dashed). */
    String sid();

    long ago();

    /** The wire discriminator {@code "t"}. */
    default String type() {
        return switch (this) {
            case Join j -> JOIN;
            case Info i -> INFO;
            case Quit q -> QUIT;
        };
    }

    /**
     * A player's session started, or a join re-sent after {@code resync.unknown} (same sid and original time).
     *
     * @param uuid    dashed, as the proxy sees it (the panel keys the player the same way as in {@code /login})
     * @param loginId the {@code /login} answer's {@code loginId} of this connection; null after fail-open or reload
     * @param backend current backend server name; nullable
     * @param bedrock Floodgate player
     * @param settings the client's settings; null until the client sent them
     */
    record Join(String sid, long ago, String uuid, String name, String ip, Long loginId, Integer protocol,
                String backend, boolean bedrock, String brand, String locale, ClientSettings settings) implements SyncEvent {

        public Join(String sid, long ago, String uuid, String name, String ip, Long loginId, Integer protocol,
                    String backend, boolean bedrock, String brand, String locale) {
            this(sid, ago, uuid, name, ip, loginId, protocol, backend, bedrock, brand, locale, null);
        }
    }

    /**
     * Changed client details of an open session; null fields are unchanged. {@code locale} is BCP 47 ("ru-RU").
     * {@code settings} is sent whole, only when it changed.
     */
    record Info(String sid, long ago, String brand, String locale, String backend, ClientSettings settings) implements SyncEvent {

        public Info(String sid, long ago, String brand, String locale, String backend) {
            this(sid, ago, brand, locale, backend, null);
        }
    }

    /**
     * The session ended.
     *
     * @param reason {@link #REASON_QUIT}, {@link #REASON_KICKED} (the plugin executed a Kordon kick) or
     *               {@link #REASON_GONE} (the plugin does not know this sid, or the connection vanished)
     */
    record Quit(String sid, long ago, String reason) implements SyncEvent {

        public static final String REASON_QUIT = "quit";
        public static final String REASON_KICKED = "kicked";
        public static final String REASON_GONE = "gone";
    }
}
